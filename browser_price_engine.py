"""Explicit, host-only interactive browser sessions for price preview.

The API layer owns authentication and product permissions. Dedicated profiles
retain only this feature's browser session; daily browser profiles are untouched.
Each Playwright instance is created and used on one worker thread.
"""
from __future__ import annotations

import copy
import hashlib
import json
import os
import queue
import re
import secrets
import shutil
import threading
import time
from concurrent.futures import Future, TimeoutError as FutureTimeout
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

from fastapi import HTTPException

import price_capture

JOB_TTL = 15 * 60
PREVIEW_TTL = 2 * 60
MAX_HISTORY = 8
VERIFY_TIMEOUT = 12
READ_TIMEOUT = 15
STOP_GRACE = 2
_lock = threading.RLock()
_jobs: dict[str, dict] = {}
_active_id: str | None = None
_directory: Path | None = None


def init_engine(directory: Path) -> None:
    """Keep dedicated login profiles under the application's private data root."""
    global _directory
    _directory = Path(directory).resolve()


def _profile_path(target: dict, channel: str, *, create: bool = True) -> Path:
    if _directory is None:
        raise HTTPException(503, '采价浏览器尚未初始化，请重启本地服务。')
    # A web session owns each live job; the stable application user owns the
    # disk profile, so logging back into Midoo does not discard the shop login.
    user = target.get('_profile_user')
    if not isinstance(user, str) or not user or len(user) > 128:
        raise HTTPException(400, '当前登录用户无法建立专用采价浏览器，请重新登录。')
    host = (urlsplit(target['source_url']).hostname or '').lower().rstrip('.')
    key = json.dumps([user, str(target.get('platform', '')).strip().casefold(),
                      str(target.get('store', '')).strip(), host, channel], ensure_ascii=False)
    digest = hashlib.sha256(key.encode()).hexdigest()
    folder = _directory / 'browser-price-profiles' / digest
    # All components below DATA_DIR are generated by this module, never supplied
    # as a path by a URL or an HTTP caller. Do not follow a redirected profile.
    base = _directory / 'browser-price-profiles'
    if base.is_symlink() or folder.is_symlink() or not folder.resolve().is_relative_to(_directory):
        raise HTTPException(503, '采价浏览器资料目录无效，请联系管理员检查。')
    if create:
        folder.mkdir(parents=True, exist_ok=True)
    return folder


def clear_profile(target: dict) -> dict:
    """Clear only this app user's dedicated login for the selected shop/site."""
    with _lock:
        folders = [_profile_path(target, channel, create=False) for channel in ('msedge', 'chrome')]
        for job in _jobs.values():
            if job['_done'].is_set():
                continue
            if any(_profile_path(job['_target'], channel, create=False) in folders for channel in ('msedge', 'chrome')):
                raise HTTPException(409, '此店铺的采价窗口正在使用登录资料，请先关闭窗口再清除。')
        try:
            for folder in folders:
                # Re-resolve immediately before recursive deletion. Never remove
                # any path supplied by the browser, a URL, or a client payload.
                root = (_directory / 'browser-price-profiles').resolve()
                resolved = folder.resolve()
                if folder.is_symlink() or resolved.parent != root or not resolved.is_relative_to(_directory):
                    raise HTTPException(503, '采价浏览器资料目录无效，请联系管理员检查。')
                if folder.exists():
                    shutil.rmtree(folder)
        except OSError:
            raise HTTPException(409, '登录资料暂时被浏览器占用，请关闭该店铺的专用窗口后重试。') from None
    return {'ok': True, 'message': '已清除此店铺在本机采价浏览器中的登录资料；下次打开需重新登录。'}


def _browsers() -> list[tuple[str, str]]:
    roots = [os.environ.get('PROGRAMFILES(X86)', r'C:\Program Files (x86)'),
             os.environ.get('PROGRAMFILES', r'C:\Program Files'),
             os.environ.get('LOCALAPPDATA', '')]
    found = []
    for channel, label, tail in (
        ('msedge', 'Microsoft Edge', 'Microsoft/Edge/Application/msedge.exe'),
        ('chrome', 'Google Chrome', 'Google/Chrome/Application/chrome.exe'),
    ):
        if any(root and (Path(root) / tail).is_file() for root in roots):
            found.append((channel, label))
    return found


def _runtime_ready() -> bool:
    try:
        # This also catches incomplete frozen builds with missing Node/CLI data.
        from playwright._impl._driver import compute_driver_executable
        from playwright.sync_api import Error as PlaywrightError, sync_playwright
    except (ImportError, OSError, AttributeError):
        return False
    try:
        return callable(sync_playwright) and all(Path(path).is_file() for path in compute_driver_executable())
    except (PlaywrightError, OSError, AttributeError):
        # The SDK raises its own Error before returning paths when Node was
        # omitted from a frozen bundle. Report unavailable, not an API 500.
        return False


def available() -> dict:
    browsers = _browsers()
    if not _runtime_ready():
        return {'available': False, 'browser': '', 'note': '浏览器辅助组件不完整，请更新完整软件包；不会自动下载组件。'}
    if not browsers:
        return {'available': False, 'browser': '', 'note': '主机未检测到 Microsoft Edge 或 Google Chrome，请先安装官方浏览器。'}
    return {'available': True, 'browser': browsers[0][1],
            'persistent_login': True,
            'note': '专用采价浏览器按当前用户、店铺和站点保留本机登录。首次请自行登录，平台仍可能要求重新验证；选好 SKU 后读取并确认报价。'}


def _public_url(value: str) -> str:
    try:
        parts = urlsplit(value)
        # Only site/path are useful in status. Query strings can contain tokens.
        if parts.scheme not in {'http', 'https'}:
            return ''
        host = parts.hostname or ''
        authority = '[' + host + ']' if ':' in host else host
        if parts.port is not None:
            authority += ':' + str(parts.port)
        return urlunsplit((parts.scheme, authority, parts.path, '', ''))[:1800]
    except ValueError:
        return ''


def _job_view(job: dict) -> dict:
    result = copy.deepcopy({key: job[key] for key in (
        'id', 'state', 'message', 'browser', 'listing_id', 'title', 'url', 'candidates', 'notices')})
    for value in result['candidates']:
        value.pop('url', None)
    return result


def _prune() -> None:
    finished = [job for job in _jobs.values() if job['_done'].is_set()]
    for old in sorted(finished, key=lambda value: value['_created'])[:-MAX_HISTORY]:
        _jobs.pop(old['id'], None)


def _owned(owner: str, job_id: str) -> dict:
    job = _jobs.get(job_id) if isinstance(job_id, str) else None
    if not job or not isinstance(owner, str) or job['_owner'] != owner:
        raise HTTPException(404, '浏览器辅助任务不存在或不属于当前会话。')
    if time.monotonic() - job['_created'] >= JOB_TTL and not job['_done'].is_set():
        _cancel(job, '辅助窗口已超时关闭，请重新打开。')
    return job


def _cancel(job: dict, message: str) -> None:
    job['_stop'].set()
    job['_commands'].put(('close', None, None))
    job.update(state='closed', message=message, candidates=[], notices=[])
    job['_preview_at'] = 0


def start(owner: str, target: dict) -> dict:
    global _active_id
    if not isinstance(owner, str) or not owner:
        raise HTTPException(400, '当前会话无效，请重新登录。')
    if not isinstance(target, dict) or not isinstance(target.get('listing_id'), str):
        raise HTTPException(400, '请选择有效的平台价格记录。')
    try:
        url = price_capture.safe_validate_url(target.get('source_url'))
    except price_capture.PriceCaptureError as exc:
        raise HTTPException(400, exc.message) from None
    capability = available()
    if not capability['available']:
        raise HTTPException(503, capability['note'])
    # Validate before launching; the API is the only authority assigning this
    # stable profile identity. It is never taken from the client's payload.
    if not isinstance(target.get('_profile_user'), str) or not target['_profile_user']:
        raise HTTPException(400, '缺少当前登录用户，无法打开专用采价浏览器。')
    with _lock:
        _prune()
        if _active_id and _active_id in _jobs and not _jobs[_active_id]['_done'].is_set():
            raise HTTPException(409, '主机已有浏览器辅助窗口，请先完成或关闭当前任务。')
        identity = secrets.token_urlsafe(24)
        job = {'id': identity, 'state': 'starting', 'message': '正在主机打开独立商品浏览器…',
               'browser': capability['browser'], 'listing_id': target['listing_id'],
               'title': '', 'url': _public_url(url), 'candidates': [], 'notices': [],
               '_owner': owner, '_target': copy.deepcopy(target), '_source_url': url,
               '_created': time.monotonic(), '_preview_at': 0, '_commands': queue.Queue(),
               '_stop': threading.Event(), '_done': threading.Event(), '_verifying': False}
        worker = threading.Thread(target=_worker, args=(job,), name='midoo-price-browser', daemon=True)
        job['_thread'] = worker
        _jobs[identity] = job
        _active_id = identity
        worker.start()
        return _job_view(job)


def snapshot(owner: str, job_id: str) -> dict:
    with _lock:
        job = _owned(owner, job_id)
        if job['state'] == 'preview' and time.monotonic() - job['_preview_at'] >= PREVIEW_TTL:
            job.update(state='ready', candidates=[], message='报价预览已过期，请重新读取当前页面。')
        return _job_view(job)


def read(owner: str, job_id: str) -> dict:
    with _lock:
        job = _owned(owner, job_id)
        if job['state'] in {'starting', 'reading'} or job['_verifying']:
            raise HTTPException(409, '窗口正在加载或读取，请稍后再试。')
        if job['state'] in {'closed', 'error'} or job['_done'].is_set():
            raise HTTPException(409, '辅助窗口已关闭，请重新打开。')
        job.update(state='reading', message='正在读取当前可见的商品报价…', candidates=[])
        job['_preview_at'] = 0
        job['_commands'].put(('read', None, None))
        return _job_view(job)


def close(owner: str, job_id: str) -> dict:
    with _lock:
        job = _owned(owner, job_id)
        _cancel(job, '辅助窗口已关闭，未确认的报价不会写入。')
        return _job_view(job)


def candidate(owner: str, job_id: str, candidate_id: str) -> tuple[dict, dict]:
    """Recheck the live page on the worker before returning a server-held quote.

    The caller must run this synchronous operation in a threadpool, then perform
    its normal permission/config-revision checks before committing any result.
    """
    with _lock:
        job = _owned(owner, job_id)
        if job['state'] != 'preview' or job['_done'].is_set() or job['_verifying']:
            raise HTTPException(409, '请先读取并选择一条有效报价。')
        if time.monotonic() - job['_preview_at'] >= PREVIEW_TTL:
            job.update(state='ready', candidates=[], message='报价预览已过期，请重新读取。')
            raise HTTPException(409, '报价预览已过期，请重新读取当前页面。')
        value = next((item for item in job['candidates'] if item['id'] == candidate_id), None)
        if value is None:
            raise HTTPException(409, '所选报价已变化，请重新读取并选择。')
        future = Future()
        job['_verifying'] = True
        job['_commands'].put(('verify', copy.deepcopy(value), future))
    try:
        return future.result(timeout=VERIFY_TIMEOUT)
    except FutureTimeout:
        future.cancel()
        with _lock:
            _cancel(job, '页面核验超时，辅助窗口已关闭；本次未写入，请重新打开。')
        raise HTTPException(409, '页面核验超时，本次未写入，请重新读取或关闭后重试。') from None


def _network_guard(url: str) -> None:
    normalized = price_capture.safe_validate_url(url)
    parts = urlsplit(normalized)
    # A new DNS resolution is checked for each request, including redirects.
    # Browser routing does not weaken or replace the static fetcher's socket pin.
    price_capture._resolve_public_addresses(parts.hostname, 443 if parts.scheme == 'https' else 80)


def _safe_route(route) -> None:
    try:
        _network_guard(route.request.url)
        route.continue_()
    except Exception:
        try:
            route.abort('blockedbyclient')
        except Exception:
            pass


def _playwright_factory():
    from playwright.sync_api import sync_playwright
    return sync_playwright()


def _request_driver_stop(manager) -> None:
    """Interrupt a stuck renderer through its owning event loop, not its API.

    Playwright's sync API has no timeout for evaluate(). Its fixed-version
    context manager owns this loop/pipe. Scheduling a pipe shutdown lets its
    connection cleanup close only the driver and browsers it created, without
    searching for or killing any of the user's normal browser processes.
    """
    try:
        manager._loop.call_soon_threadsafe(manager._client._transport.request_stop)
    except (AttributeError, RuntimeError):
        pass


def _watch(job: dict, manager) -> None:
    stop_at = None
    while not job['_done'].wait(0.1):
        now = time.monotonic()
        with _lock:
            if not job['_stop'].is_set():
                if now - job['_created'] >= JOB_TTL:
                    _cancel(job, '辅助窗口已超时关闭，请重新打开。')
                elif job.get('_read_started') and now - job['_read_started'] > READ_TIMEOUT:
                    _cancel(job, '当前页面未响应，辅助窗口已关闭；本次未写入，请重新打开。')
            if job['_stop'].is_set() and stop_at is None:
                stop_at = now
        if stop_at is not None and now - stop_at >= STOP_GRACE:
            _request_driver_stop(manager)
            return


def _capture(page, target: dict) -> dict:
    import browser_price_parser
    url = page.url
    _network_guard(url)
    value = page.evaluate(browser_price_parser.SNAPSHOT_JS)
    if not isinstance(value, dict):
        raise HTTPException(409, '页面尚未加载完成，请在商品窗口查看后重新读取。')
    value['url'] = url
    parsed = browser_price_parser.parse_snapshot(value, target)
    if not isinstance(parsed, dict):
        raise HTTPException(409, '页面未提供可核验的商品报价。')
    values = []
    for item in parsed.get('candidates', [])[:12]:
        if not isinstance(item, dict):
            continue
        identifier, currency, evidence = item.get('id'), item.get('currency'), item.get('evidence')
        if (not isinstance(identifier, str) or not 1 <= len(identifier) <= 80 or
                not isinstance(currency, str) or not re.fullmatch(r'[A-Z]{3}', currency) or
                not isinstance(evidence, str) or not evidence.strip()):
            continue
        try:
            price = price_capture._price(item.get('price'))
        except price_capture.PriceCaptureError:
            continue
        values.append({'id': identifier, 'price': price, 'currency': currency,
                       'evidence': evidence[:600], 'title': str(value.get('title', ''))[:300],
                       'source': 'browser_confirmed', 'url': url,
                       'label': str(item.get('label', '可见商品报价'))[:160],
                       'currency_inferred': bool(item.get('currency_inferred')),
                       'require_variant_confirmation': bool(item.get('require_variant_confirmation', True)),
                       'require_currency_confirmation': bool(item.get('require_currency_confirmation', True))})
    return {'title': str(value.get('title', ''))[:300], 'url': _public_url(url), 'candidates': values,
            'message': str(parsed.get('message', '请核对规格、地区与币种，再选择报价确认。'))[:500],
            'notices': [str(item)[:500] for item in parsed.get('notices', [])[:8]],
            'needs_action': bool(parsed.get('needs_action'))}


def _update_capture(job: dict, captured: dict) -> None:
    with _lock:
        if job['_stop'].is_set():
            return
        job.update({k: captured[k] for k in ('title', 'url', 'candidates', 'message', 'notices')})
        job['state'] = 'preview' if captured['candidates'] else 'needs_action'
        job['_preview_at'] = time.monotonic() if captured['candidates'] else 0


def _worker(job: dict) -> None:
    global _active_id
    browser = context = manager = None
    pending_futures = []
    try:
        manager = _playwright_factory()
        playwright = manager.__enter__()
        watcher = threading.Thread(target=_watch, args=(job, manager), name='midoo-price-browser-watch', daemon=True)
        watcher.start()
        for channel, label in _browsers():
            if job['_stop'].is_set():
                return
            try:
                context = playwright.chromium.launch_persistent_context(
                    user_data_dir=str(_profile_path(job['_target'], channel)),
                    channel=channel, headless=False, chromium_sandbox=True,
                    timeout=15000, handle_sigint=False, handle_sigterm=False, handle_sighup=False,
                    accept_downloads=False, service_workers='block', permissions=[],
                    ignore_https_errors=False, no_viewport=True)
                browser = context.browser
                with _lock:
                    job['browser'] = label
                break
            except Exception:
                # Try the other installed official browser, never change
                # sandbox/certificate options to force a browser to launch.
                if context is not None:
                    try:
                        context.close()
                    except Exception:
                        pass
                context = browser = None
                continue
        if context is None:
            raise HTTPException(503, '无法启动独立浏览器，可能受浏览器策略限制；请检查主机 Edge/Chrome 是否可正常打开。')
        if job['_stop'].is_set():
            return
        context.set_default_timeout(6000)
        context.route('**/*', _safe_route)
        context.route_web_socket('**/*', lambda socket: socket.close())
        # Normal sign-in flows may open a popup. They stay inside the same
        # guarded context; only the initial product page can supply a quote.
        def secure_page(opened):
            if len(context.pages) > 4:
                opened.close()
                return
            opened.on('download', lambda download: download.cancel())
            opened.on('dialog', lambda dialog: dialog.dismiss())
        restored = list(context.pages)
        page = context.new_page()
        secure_page(page)
        for previous in restored:
            previous.close()
        context.on('page', secure_page)
        loading_message = '请在专用浏览器登录并选好 SKU 与地区，再回来读取；本店铺登录状态会保留在本机，平台仍可能要求验证。'
        try:
            _network_guard(job['_source_url'])
            response = page.goto(job['_source_url'], wait_until='domcontentloaded', timeout=20000)
            if response is not None and response.status >= 400:
                loading_message = '商品站点返回访问限制或错误，请在独立窗口检查页面；本次尚未采集价格。'
        except Exception:
            loading_message = '商品页尚未完成加载或受到访问限制。请在独立窗口查看；如出现登录或验证，请由你操作后重新读取。'
        with _lock:
            if job['_stop'].is_set():
                return
            job.update(state='ready', message=loading_message)
        previous_url = page.url
        while not job['_stop'].is_set() and time.monotonic() - job['_created'] < JOB_TTL:
            if page.is_closed() or (browser is not None and not browser.is_connected()):
                break
            if page.url != previous_url:
                previous_url = page.url
                with _lock:
                    job.update(candidates=[], state='ready', url=_public_url(previous_url),
                               message='页面已切换，请确认仍是目标商品，再重新读取报价。')
                    job['_preview_at'] = 0
            try:
                command, value, future = job['_commands'].get_nowait()
            except queue.Empty:
                page.wait_for_timeout(150)
                continue
            if command == 'close':
                break
            if future is not None:
                pending_futures.append(future)
            try:
                if job['_stop'].is_set():
                    raise HTTPException(409, '辅助窗口已关闭，本次未写入。')
                with _lock:
                    job['_read_started'] = time.monotonic()
                captured = _capture(page, job['_target'])
                if command == 'read':
                    _update_capture(job, captured)
                elif command == 'verify':
                    current = next((item for item in captured['candidates'] if
                                    item['price'] == value['price'] and item['currency'] == value['currency']
                                    and item['evidence'] == value['evidence']), None)
                    if current is None or job['_stop'].is_set():
                        _update_capture(job, captured)
                        raise HTTPException(409, '页面报价或规格已变化，本次未写入。请重新读取并确认。')
                    if not future.done():
                        future.set_result((copy.deepcopy(job['_target']), current))
            except Exception as exc:
                error = exc if isinstance(exc, HTTPException) else HTTPException(409, '无法读取当前页面，请在独立窗口完成加载、规格选择或验证后重试。')
                if command == 'read':
                    with _lock:
                        if not job['_stop'].is_set():
                            job.update(state='needs_action', candidates=[], message=error.detail)
                if future is not None and not future.done():
                    future.set_exception(error)
            finally:
                with _lock:
                    job['_read_started'] = None
                if command == 'verify':
                    with _lock:
                        job['_verifying'] = False
                if future in pending_futures:
                    pending_futures.remove(future)
        with _lock:
            if job['state'] != 'closed':
                _cancel(job, '辅助窗口已关闭或达到15分钟时限，未确认的报价不会写入。')
    except Exception as exc:
        with _lock:
            if not job['_stop'].is_set():
                job.update(state='error', candidates=[], message=exc.detail if isinstance(exc, HTTPException)
                           else '浏览器辅助未能启动，请确认完整组件和 Edge/Chrome 可用。')
    finally:
        # The worker owns all Playwright objects. Its context-manager closes
        # the driver as well; no user/browser process is searched or killed.
        for resource in (context, browser):
            if resource is not None:
                try:
                    resource.close()
                except Exception:
                    pass
        if manager is not None:
            try:
                manager.__exit__(None, None, None)
            except Exception:
                pass
        with _lock:
            job['candidates'] = []
            job['_preview_at'] = 0
            while True:
                try:
                    _, _, future = job['_commands'].get_nowait()
                    if future is not None:
                        pending_futures.append(future)
                except queue.Empty:
                    break
            for future in pending_futures:
                if not future.done():
                    future.set_exception(HTTPException(409, '辅助窗口已关闭，本次未写入。'))
            job['_done'].set()
            if _active_id == job['id']:
                _active_id = None
            _prune()


def shutdown() -> None:
    with _lock:
        jobs = [job for job in _jobs.values() if not job['_done'].is_set()]
        for job in jobs:
            _cancel(job, '本地服务正在关闭，未确认的报价不会写入。')
    deadline = time.monotonic() + 40
    for job in jobs:
        remaining = max(0, deadline - time.monotonic())
        job['_thread'].join(timeout=remaining)
